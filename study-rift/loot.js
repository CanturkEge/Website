const label = {
  hp: "maksimum can",
  mp: "maksimum mana",
  xp: "XP / doğru",
  mana: "mana / doğru",
  defense: "hasar azaltma",
  gold: "altın / doğru",
};
export const GEAR = bases.flatMap(
  ([id, name, slot, icon, k, v, k2, v2, desc], index) =>
    rarity.map(([r, prefix, m], tier) => {
      const stats = {
        [k]: Math.max(1, Math.round(v * m)),
        [k2]: Math.max(1, Math.round(v2 * m)),
      };
      const special = tier >= 2 && index % 6 === 0 ? "eliminate" : null;
      return {
        id: `gear-${id}-${r}`,
        name: `${prefix} ${name}`,
        family: id,
        slot,
        icon,
        rarity: r,
        desc,
        effect:
          Object.entries(stats)
            .map(([key, value]) => `+${value} ${label[key]}`)
            .join(" · ") + (special ? " · Eleme yeteneği" : ""),
        ...stats,
        ...(special ? { skill: special } : {}),
      };
    }),
);
